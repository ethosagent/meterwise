package main

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

var numberRe = regexp.MustCompile(`^(\d{4})_`)

// lintMigrations enforces the migration rules (docs: .claude/rules/migrations.md):
// file name NNNN_<feature>.sql with a matching `-- feature:` header, unique
// numbers, a non-empty Down section, and one feature per file: a migration may
// create tables and alter only tables owned by its own feature, where a
// table's owner is the feature of the migration that created it.
func lintMigrations(ms []migration) []string {
	var problems []string
	add := func(format string, a ...any) { problems = append(problems, fmt.Sprintf(format, a...)) }
	owner := map[string]string{}
	numbers := map[string]string{}
	for _, m := range ms {
		if m.Feature == "" {
			add("%s: name must be NNNN_<feature>.sql (lowercase feature)", m.File)
			continue
		}
		if n := numberRe.FindString(m.File); numbers[n] != "" {
			add("%s: number %s already used by %s", m.File, strings.TrimSuffix(n, "_"), numbers[n])
		} else {
			numbers[n] = m.File
		}
		if m.headerFeature != m.Feature {
			add("%s: first lines need `-- feature: %s` (found %q)", m.File, m.Feature, m.headerFeature)
		}
		if !m.HasDown {
			add("%s: missing a non-empty `-- +goose Down` section (migrations are reversible)", m.File)
		}
		for _, t := range m.Created {
			if o, dup := owner[t]; dup {
				add("%s: creates table %s already created by feature %s", m.File, t, o)
			}
			owner[t] = m.Feature
		}
		for _, t := range m.Touched {
			switch o, known := owner[t]; {
			case !known:
				add("%s: touches table %s, which no earlier migration creates", m.File, t)
			case o != m.Feature:
				add("%s: touches table %s owned by feature %s; a migration changes one feature's tables only (add a migration named for %s)", m.File, t, o, o)
			}
		}
	}
	sort.Strings(problems)
	return problems
}

// renderSchema renders docs/schema.md from the migrations.
func renderSchema(ms []migration) []byte {
	var b strings.Builder
	b.WriteString("<!-- @generated by cmd/gen from internal/store/migrations. DO NOT EDIT; run `go run ./cmd/gen`. -->\n")
	b.WriteString("# Database schema\n\nOne section per table, in creation order. Owner = the feature whose migration created it.\n")
	if len(ms) == 0 {
		b.WriteString("\nNo migrations yet.\n")
		return []byte(b.String())
	}
	var order []table
	byName := map[string]int{}
	for _, m := range ms {
		for _, t := range m.tables {
			byName[t.Name] = len(order)
			order = append(order, t)
		}
		for name, cols := range m.adds {
			if i, ok := byName[name]; ok {
				order[i].Columns = append(order[i].Columns, cols...)
			}
		}
	}
	for _, t := range order {
		fmt.Fprintf(&b, "\n## %s\n\nOwner: `%s` (created in `%s`)\n\n| Column | Definition | Migration |\n|---|---|---|\n", t.Name, t.Feature, t.Migration)
		for _, c := range t.Columns {
			fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", c.Name, strings.ReplaceAll(c.Def, "|", `\|`), c.Migration)
		}
	}
	return []byte(b.String())
}
