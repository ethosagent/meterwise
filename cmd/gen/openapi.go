package main

import (
	"encoding/json"
	"fmt"
	"reflect"
	"strings"

	"github.com/ethosagent/meterwise/internal/contract"
)

func schemaFor(t reflect.Type) (map[string]any, error) {
	switch t {
	case reflect.TypeFor[contract.MicroUSD]():
		return map[string]any{"type": "string", "pattern": `^-?\d+\.\d{6}$`, "description": "decimal USD, six places"}, nil
	case reflect.TypeFor[contract.Code]():
		codes := []string{}
		for _, s := range contract.Errors() {
			codes = append(codes, string(s.Code))
		}
		return map[string]any{"type": "string", "enum": codes}, nil
	}
	switch t.Kind() {
	case reflect.String:
		return map[string]any{"type": "string"}, nil
	case reflect.Bool:
		return map[string]any{"type": "boolean"}, nil
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint32, reflect.Uint64:
		return map[string]any{"type": "integer"}, nil
	case reflect.Float64:
		return map[string]any{"type": "number"}, nil
	case reflect.Slice:
		el, err := schemaFor(t.Elem())
		if err != nil {
			return nil, err
		}
		return map[string]any{"type": "array", "items": el}, nil
	case reflect.Struct:
		return map[string]any{"$ref": "#/components/schemas/" + t.Name()}, nil
	}
	return nil, fmt.Errorf("gen: no OpenAPI mapping for Go type %s", t)
}

func objectSchema(d contract.DTO) (map[string]any, error) {
	props := map[string]any{}
	required := []string{}
	for i := range d.Type.NumField() {
		f := d.Type.Field(i)
		name, optional, skip := fieldInfo(f)
		if skip {
			continue
		}
		s, err := schemaFor(f.Type)
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", d.Name, f.Name, err)
		}
		props[name] = s
		if !optional {
			required = append(required, name)
		}
	}
	return map[string]any{"type": "object", "properties": props, "required": required}, nil
}

func operation(r contract.Route) map[string]any {
	op := map[string]any{
		"summary":     r.Summary,
		"operationId": operationID(r),
		"responses": map[string]any{
			"200":     map[string]any{"description": "OK", "content": jsonContent(r.Response)},
			"default": map[string]any{"description": "Error", "content": jsonContent("ErrorBody")},
		},
	}
	if r.Public {
		op["security"] = []any{}
	} else {
		op["security"] = []any{map[string]any{"bearerAuth": []string{}}}
		op["x-permission"] = string(r.Permission)
	}
	return op
}

func jsonContent(dto string) map[string]any {
	return map[string]any{"application/json": map[string]any{"schema": map[string]any{"$ref": "#/components/schemas/" + dto}}}
}

func operationID(r contract.Route) string {
	var b strings.Builder
	b.WriteString(strings.ToLower(r.Method))
	for _, seg := range strings.FieldsFunc(r.Pattern, func(c rune) bool { return c == '/' || c == '{' || c == '}' }) {
		b.WriteString(strings.ToUpper(seg[:1]) + seg[1:])
	}
	return b.String()
}

func genOpenAPI() ([]byte, error) {
	schemas := map[string]any{}
	for _, d := range contract.DTOs() {
		s, err := objectSchema(d)
		if err != nil {
			return nil, err
		}
		schemas[d.Name] = s
	}
	paths := map[string]any{}
	for _, r := range contract.Routes() {
		item, _ := paths[r.Pattern].(map[string]any)
		if item == nil {
			item = map[string]any{}
			paths[r.Pattern] = item
		}
		item[strings.ToLower(r.Method)] = operation(r)
	}
	doc := map[string]any{
		"openapi": "3.1.0",
		"info":    map[string]any{"title": "Meterwise control plane", "version": "0.0.0", "description": "Generated by cmd/gen from internal/contract. Do not edit."},
		"paths":   paths,
		"components": map[string]any{
			"schemas":         schemas,
			"securitySchemes": map[string]any{"bearerAuth": map[string]any{"type": "http", "scheme": "bearer"}},
		},
	}
	b, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("gen: marshal openapi: %w", err)
	}
	return append(b, '\n'), nil
}
