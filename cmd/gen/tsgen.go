package main

import (
	"fmt"
	"reflect"
	"strings"

	"github.com/ethosagent/meterwise/internal/contract"
)

const generatedBanner = "// @generated by cmd/gen from internal/contract. DO NOT EDIT; run `go run ./cmd/gen`.\n"

// tsType maps a Go type to its TypeScript spelling. Unsupported kinds return
// an error so a new DTO field type is a loud generator failure, not a silent any.
func tsType(t reflect.Type) (string, error) {
	switch t {
	case reflect.TypeFor[contract.Code]():
		return "ErrorCode", nil
	case reflect.TypeFor[contract.MicroUSD]():
		return "string", nil // decimal string (ruling R12)
	case reflect.TypeFor[contract.Theme]():
		return "Theme", nil
	case reflect.TypeFor[contract.Role]():
		return "Role", nil
	case reflect.TypeFor[contract.InvitationStatus]():
		return "InvitationStatus", nil
	case reflect.TypeFor[contract.AuditAction]():
		return "AuditAction", nil
	case reflect.TypeFor[map[string]any]():
		return "Record<string, unknown>", nil
	}
	switch t.Kind() {
	case reflect.Pointer:
		return tsType(t.Elem())
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint32, reflect.Uint64, reflect.Float64:
		return "number", nil
	case reflect.Slice:
		el, err := tsType(t.Elem())
		if err != nil {
			return "", err
		}
		return el + "[]", nil
	case reflect.Struct:
		return dtoName(t), nil
	}
	return "", fmt.Errorf("gen: no TypeScript mapping for Go type %s", t)
}

// dtoName is the API name of a struct type: the DTOs() name, else the Go name.
func dtoName(t reflect.Type) string {
	for _, d := range contract.DTOs() {
		if d.Type == t {
			return d.Name
		}
	}
	return t.Name()
}

// fieldInfo reads a struct field's JSON name and optionality.
func fieldInfo(f reflect.StructField) (name string, optional, skip bool) {
	tag := f.Tag.Get("json")
	if tag == "-" || !f.IsExported() {
		return "", false, true
	}
	name, opts, _ := strings.Cut(tag, ",")
	if name == "" {
		name = f.Name
	}
	return name, strings.Contains(opts, "omitempty"), false
}

func tsInterface(d contract.DTO) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", d.Name)
	for i := range d.Type.NumField() {
		f := d.Type.Field(i)
		name, optional, skip := fieldInfo(f)
		if skip {
			continue
		}
		ty, err := tsType(f.Type)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", d.Name, f.Name, err)
		}
		if f.Type.Kind() == reflect.Pointer && !optional {
			ty += " | null" // a pointer without omitempty is sent as null
		}
		q := ""
		if optional {
			q = "?"
		}
		fmt.Fprintf(&b, "  %s%s: %s;\n", name, q, ty)
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// tsConstTuple writes `export const NAME = [...] as const;` and the union type derived from it.
func tsConstTuple[T ~string](b *strings.Builder, name, typ string, vals []T) {
	b.WriteString("export const " + name + " = [")
	for i, v := range vals {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", string(v))
	}
	b.WriteString("] as const;\n\nexport type " + typ + " = (typeof " + name + ")[number];\n\n")
}

func genContractTS() ([]byte, error) {
	var b strings.Builder
	b.WriteString(generatedBanner)
	b.WriteString("\nexport const ERROR_CODES = [\n")
	specs := contract.Errors()
	for _, s := range specs {
		fmt.Fprintf(&b, "  %q,\n", s.Code)
	}
	b.WriteString("] as const;\n\nexport type ErrorCode = (typeof ERROR_CODES)[number];\n\n")
	tsConstTuple(&b, "THEMES", "Theme", contract.Themes())
	tsConstTuple(&b, "ROLES", "Role", contract.Roles())
	tsConstTuple(&b, "INVITATION_STATUSES", "InvitationStatus", contract.InvitationStatuses())
	tsConstTuple(&b, "AUDIT_ACTIONS", "AuditAction", contract.AuditActions())
	b.WriteString("export const ERROR_STATUS: Record<ErrorCode, number> = {\n")
	for _, s := range specs {
		fmt.Fprintf(&b, "  %s: %d,\n", s.Code, s.Status)
	}
	b.WriteString("};\n\n")
	for _, d := range contract.DTOs() {
		s, err := tsInterface(d)
		if err != nil {
			return nil, err
		}
		b.WriteString(s + "\n")
	}
	b.WriteString("export interface RouteSpec {\n  method: string;\n  pattern: string;\n  permission: string;\n  workspaceParam?: string;\n  public: boolean;\n}\n\n")
	b.WriteString("export const ROUTES: readonly RouteSpec[] = [\n")
	for _, r := range contract.Routes() {
		ws := ""
		if r.WorkspaceParam != "" {
			ws = fmt.Sprintf(" workspaceParam: %q,", r.WorkspaceParam)
		}
		fmt.Fprintf(&b, "  { method: %q, pattern: %q, permission: %q,%s public: %t },\n", r.Method, r.Pattern, string(r.Permission), ws, r.Public)
	}
	b.WriteString("];\n")
	return []byte(b.String()), nil
}
