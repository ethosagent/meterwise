package ledger

import (
	"net/http"
	"strings"
)

// maxClientFamily caps a client family in bytes (the calls.client and sessions.client columns are text, but the
// dashboard groups by it, so it stays short).
const maxClientFamily = 64

// ClientFamily names the client of a request from its User-Agent alone: the first product token, without its
// version, lower-cased, printable ASCII only and at most 64 bytes ("opencode/1.2 (linux)" is "opencode").
// "" means the header is absent or has no usable token; the store keeps that as NULL and the UI shows
// "unknown". No credential header is read (rule 2): only User-Agent is looked at.
//
// The OpenAI and Anthropic SDKs (generated by Stainless) are split by language, from X-Stainless-Lang or the
// "OpenAI/Python 1.2" User-Agent: openai-python, openai-node, anthropic-python, anthropic-node. A client that
// sends the literal "unknown" is stored as NULL, so the UI's "unknown" is never a real client. Every other
// User-Agent (opencode and demo-traffic in the committed fixtures; Claude Code, Codex and curl, whose strings
// no fixture holds) is the generic product token; none is guessed.
func ClientFamily(h http.Header) string {
	tok, _, _ := strings.Cut(strings.TrimSpace(h.Get("User-Agent")), " ")
	tok, sub, _ := strings.Cut(tok, "/")
	fam := familyToken(tok)
	if fam == unknownFamily {
		return ""
	}
	if fam == "openai" || fam == "anthropic" {
		if lang := sdkLang(h, sub); lang != "" {
			return fam + "-" + lang
		}
	}
	return fam
}

// unknownFamily is the literal the UI shows for NULL; a client that sends it is stored as NULL too, so a
// ?client=unknown filter means "no client" only.
const unknownFamily = "unknown"

// sdkLang is "python" or "node" for the Stainless-generated OpenAI and Anthropic SDKs, from X-Stainless-Lang
// (python, js) or, when absent, the second half of their "OpenAI/Python 1.2" User-Agent. Any other language
// is "" so the family stays the generic product token.
func sdkLang(h http.Header, uaSub string) string {
	lang := strings.ToLower(h.Get("X-Stainless-Lang"))
	if lang == "" {
		lang = strings.ToLower(uaSub)
	}
	switch lang {
	case "python":
		return "python"
	case "js", "node":
		return "node"
	}
	return ""
}

func familyToken(tok string) string {
	var b strings.Builder
	for i := 0; i < len(tok) && b.Len() < maxClientFamily; i++ {
		if c := tok[i]; c > ' ' && c < 0x7f {
			b.WriteByte(lowerASCII(c))
		}
	}
	return b.String()
}

func lowerASCII(c byte) byte {
	if c >= 'A' && c <= 'Z' {
		return c + 'a' - 'A'
	}
	return c
}
